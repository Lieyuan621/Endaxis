import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import type { ContingencyContractShareLayout } from '../../../packages/game-data-contract/src/mechanics.ts';
import { requireInteger, requireRecord, requireNonEmptyString } from '../src/source/primitives.ts';
import { formatGeneratedSource } from '../src/compiler/publication/formatGeneratedSource.ts';

export function compileContractShareLayouts(
  contracts: unknown,
  activities: unknown,
): ContingencyContractShareLayout[] {
  const activityTable = requireRecord(activities, 'ActivityContingencyContractTable');
  return Object.entries(requireRecord(contracts, 'ContingencyContractTable'))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([gameId, value]) => {
      const contract = requireRecord(value, gameId);
      const activityId = requireNonEmptyString(contract.activityId, `${gameId}.activityId`);
      const activity = requireRecord(activityTable[activityId], activityId);
      const maxColumn = requireInteger(activity.tagMaxColumn, `${activityId}.tagMaxColumn`);
      if (maxColumn < 1) throw new Error(`${activityId}: invalid column count`);
      const columns: Record<string, Record<string, number>> = {};
      const ids = new Set<number>();
      for (const [col, rawColumn] of Object.entries(
        requireRecord(contract.contractColMap, `${gameId}.contractColMap`),
      )) {
        if (!/^\d+$/.test(col) || Number(col) < 1 || Number(col) > maxColumn)
          throw new Error(`${gameId}: invalid column ${col}`);
        const column = requireRecord(rawColumn, col);
        const rows: Record<string, number> = {};
        for (const [row, rawEntry] of Object.entries(
          requireRecord(column.contractRowMap, `${col}.contractRowMap`),
        )) {
          const entry = requireRecord(rawEntry, row);
          const id = requireInteger(entry.tagId, `${col}.${row}.tagId`);
          if (
            !/^[123]$/.test(row) ||
            entry.column !== Number(col) ||
            entry.row !== Number(row) ||
            ids.has(id)
          )
            throw new Error(`${gameId}: inconsistent share position ${col}.${row}`);
          ids.add(id);
          rows[row] = id;
        }
        columns[col] = rows;
      }
      return { gameId, maxColumn, columns };
    });
}

export async function generateContingencyContractShareLayouts(
  tableRoot: string,
  output: string,
  check = false,
): Promise<void> {
  const [contracts, activities] = await Promise.all(
    ['ContingencyContractTable', 'ActivityContingencyContractTable'].map(async name =>
      JSON.parse(await readFile(join(tableRoot, `${name}.json`), 'utf8')),
    ),
  );
  const layouts = compileContractShareLayouts(contracts, activities);
  const source = await formatGeneratedSource(
    `// Generated by generateContingencyContractShareLayouts.ts.\nimport type { ContingencyContractShareLayout } from '../../../packages/game-data-contract/src/mechanics';\nexport const contingencyContractShareLayouts: readonly ContingencyContractShareLayout[] = ${JSON.stringify(layouts)};\n`,
    output,
  );
  if (check) {
    if ((await readFile(output, 'utf8')).replaceAll('\r\n', '\n') !== source)
      throw new Error('Contract share layouts are stale');
  } else {
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, source);
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  if (!process.argv[2]) throw new Error('Expected TableCfg directory');
  await generateContingencyContractShareLayouts(
    process.argv[2],
    'src/data/contingencyContract/shareLayouts.generated.ts',
    process.argv.includes('--check'),
  );
}
